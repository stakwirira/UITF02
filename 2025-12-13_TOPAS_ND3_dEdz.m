% DESCRIPTION: 
% This script processes and plots a 1D longitudinal depth dose profile 
% (Dose vs. Depth Z). It reads linear dose data from a CSV file, 
% converts the bin index to physical depth in centimeters, and generates 
% a highly-styled line plot. It also automatically calculates and 
% annotates the location and value of the peak dose for electrons while 
% irradiating ND3 target. The CSV file is generated by TOPAS simulation.
% -------------------------------------------------------------------------
% INPUTS: 
%   'ND3_dEdz_Profile.csv' - CSV file containing dose data vs. Z-index.
% OUTPUTS: 
%   Figure 1 - Longitudinal Depth Dose Profile plot.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

clc; clear; close all;

%% 1. Parameters
filename = 'ND3_dEdz_Profile_121325.csv'; 
z_bin_width = 0.1; % cm (From the header: "# Z in 100 bins of 0.1 cm")

%% 2. Import Data
try
    % Skip the first 8 lines of metadata
    raw_data = readmatrix(filename, 'NumHeaderLines', 8);
catch
    error('File not found. Make sure "%s" is in the current folder.', filename);
end

%% 3. Extract and Process Data
% Column 3 contains the Z-bin index (0, 1, 2...)
% Column 4 contains the Dose value
z_index = raw_data(:, 3);
dose_values = raw_data(:, 4);

% Convert Bin Index to Physical Depth (cm)
% We add 0.5 to plot the data at the *center* of the bin, not the edge.
depth_cm = (z_index * z_bin_width) + (z_bin_width / 2);

%% 4. Plotting
figure('Color', 'w');

% --- START: COLOR DEFINITION ---
% Define your bright color here (RGB Format)
% [0 0 1] = Bright Blue
% [0.85 0 0.33] = Bright Pink/Magenta
% [0 0.5 0] = Darker Green (Standard Green [0 1 0] is often too hard to read on white)
brightColor = [0, 0, 1]; 
% -------------------------------

% Plot with markers, using the custom bright color
plot(depth_cm, dose_values, '-o', ...
    'Color', brightColor, ...       % Line color
    'MarkerFaceColor', brightColor, ... % Marker fill
    'LineWidth', 1.5, ...
    'MarkerSize', 4);

% --- APPLY BRIGHT STYLING ---
ax = gca;
ax.FontSize = 12;
ax.FontWeight = 'bold';
ax.LineWidth = 1.5;
ax.XColor = brightColor;    % Axis line and tick numbers
ax.YColor = brightColor;    % Axis line and tick numbers
ax.GridColor = brightColor; % Grid lines
ax.GridAlpha = 0.2;         % Keep grid subtle

title('Longitudinal Depth Dose Profile (ND3 Target)', 'Color', brightColor, 'FontSize', 14);
xlabel('Depth Z (cm)', 'Color', brightColor, 'FontWeight', 'bold');
ylabel('Dose (Gy)', 'Color', brightColor, 'FontWeight', 'bold');

grid on;

% Add a text box with the Peak Dose info
[max_dose, max_idx] = max(dose_values);
peak_depth = depth_cm(max_idx);
stats_str = sprintf('Peak Dose: %.2e Gy\nAt Depth: %.1f cm', max_dose, peak_depth);

% Styled Annotation Box
annotation('textbox', [0.6, 0.75, 0.1, 0.1], ...
    'String', stats_str, ...
    'FitBoxToText', 'on', ...
    'BackgroundColor', 'white', ...
    'EdgeColor', brightColor, ...   % Border color
    'Color', brightColor, ...       % Text color
    'FontWeight', 'bold', ...
    'LineWidth', 1);

% Optimize view
xlim([min(depth_cm) max(depth_cm)]);
